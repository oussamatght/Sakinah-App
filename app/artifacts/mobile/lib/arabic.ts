/**
 * تطبيع النص العربي للبحث المحلي (بلا أي طلب شبكة).
 *
 * الأذكار والنصوص المخزّنة مكسوّة بالحركات بالكامل ("سُبْحَانَ اللَّهِ")،
 * والمستخدم يكتب بلا تشكيل ("سبحان الله") — فالبحث يفشل بلا تطبيع.
 * نفس القاعدة تُستخدم لبحث المصحف (searchQuranVerses) فالمطبَّق واحد
 * حتى يتصرّف البحثان بنفس الطريقة.
 */

/** التشكيل + التطويل + علامات قرآنية. */
const TASHKEEL_RE =
  /[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g;

/**
 * يوحّد الرسم العثماني/المصحفي إلى نص عربي عادي:
 * يحذف التشكيل ويوحّد الهمزات (أ إ آ ٱ → ا) والألف المقصورة والهمزة المربوطة.
 * فيصير "ٱلصَّمَدُ" == "الصمد" فيصطاده أيّهما كتبه المستخدم.
 */
export function normalizeArabic(text: string): string {
  return text
    .replace(TASHKEEL_RE, "")
    .replace(/[ٱأإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/\s+/g, " ")
    .trim();
}

